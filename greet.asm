global _start                   ; имя места в коде (метка), говорит ядру откуда начинать исполнять инструкции

section .data                   ; .data - можно: читать, менять | нельзя: исполнять
  message db "Privet, mir!", 10 ; 10 означает "enter" либо "\n"
  message_len equ $ - message   ; $ - адрес сразу после строки.

section .text                   ; .text - можно: читать, исполнять | нельзя: менять
_start:
  mov rax, 1                    ; регистр rax хранит код функции (1 значит функция write)
  mov rdi, 1                    ; первый аргумент функции (какой поток)
  lea rsi, message        ; второй аргумент функции (адрес начала строки)
  mov rdx, message_len          ; третий аргумент функции (сколько байт печатать)
  syscall                       ; передает управление ядру (после выполнения, в rax запишется результат функции)

  mov rax, 60                   ; код функции 60 = exit (ядро завершит программу)
  mov rdi, 0                    ; первый аргумент функции (ядро завершит прогу с кодом 0)
  syscall
